import { defineTable } from "convex/server";
import { v } from "convex/values";

export const fundraisingScope = v.object({
  account: v.string(),
  route: v.string(),
  apiVersion: v.string(),
  transportBinding: v.string(),
  fixtureRunId: v.string(),
});
export const confirmation = v.object({
  checkoutId: v.id("fundraisingCheckouts"),
  sessionId: v.string(),
  paymentId: v.string(),
  chargeId: v.string(),
  eventId: v.string(),
  successEventId: v.string(),
  completedAt: v.number(),
  grossCents: v.number(),
  currency: v.literal("usd"),
  feeCents: v.union(v.number(), v.null()),
  refundedCents: v.number(),
  digest: v.string(),
  factsDigest: v.string(),
  balanceTransactionId: v.union(v.string(), v.null()),
  timeBasis: v.literal("controlled-success-transition-v1"),
});
export const fundraisingTables = {
  fundraisingCheckouts: defineTable({
    refundGeneration: v.optional(v.number()),
    campaignSlug: v.string(),
    nonprofitId: v.string(),
    operationId: v.string(),
    fingerprint: v.string(),
    tokenHash: v.string(),
    originEntryId: v.optional(v.id("photoEntries")),
    creator: v.optional(v.string()),
    rulesId: v.id("campaignSettings"),
    amountCents: v.number(),
    applicationOrigin: v.string(),
    scope: fundraisingScope,
    state: v.union(
      v.literal("journaled"),
      v.literal("dispatched"),
      v.literal("uncertain"),
      v.literal("confirmed"),
    ),
    providerKey: v.string(),
    createdAt: v.number(),
    retryBefore: v.number(),
    sessionId: v.optional(v.string()),
    checkoutUrl: v.optional(v.string()),
    actor: v.literal("account-free-donor"),
    source: v.string(),
    version: v.literal(1),
  })
    .index("by_operation", ["operationId"])
    .index("by_session", ["sessionId"]),
  fundraisingRefundReads: defineTable({
    actor: v.string(),
    source: v.string(),
    version: v.literal(1),
    checkoutId: v.id("fundraisingCheckouts"),
    generation: v.number(),
    eventId: v.string(),
    digest: v.string(),
    at: v.number(),
    factsDigest: v.optional(v.string()),
    outcome: v.optional(v.string()),
    applied: v.optional(v.boolean()),
  }).index("by_checkout", ["checkoutId"]),
  fundraisingRefundObservations: defineTable({
    checkoutId: v.id("fundraisingCheckouts"),
    account: v.string(),
    refundId: v.string(),
    paymentId: v.string(),
    chargeId: v.string(),
    accepted: v.boolean(),
    amountCents: v.number(),
    status: v.string(),
    createdAt: v.number(),
    balanceTransactionId: v.union(v.string(), v.null()),
    failureBalanceTransactionId: v.union(v.string(), v.null()),
    eventId: v.string(),
    digest: v.string(),
    generation: v.number(),
    actor: v.string(),
    source: v.string(),
    at: v.number(),
    version: v.literal(1),
  })
    .index("by_checkout", ["checkoutId"])
    .index("by_refund", ["account", "refundId"]),
  fundraisingCorrections: defineTable({
    donationId: v.id("fundraisingDonations"),
    refundedCents: v.number(),
    eligibleGrossCents: v.number(),
    recognizedCommissionCents: v.number(),
    commissionAdjustmentCents: v.number(),
    refundIds: v.array(v.string()),
    eventId: v.string(),
    digest: v.string(),
    actor: v.string(),
    source: v.string(),
    at: v.number(),
    version: v.literal(1),
  }).index("by_donation", ["donationId"]),
  fundraisingCommissionObligations: defineTable({
    campaignSlug: v.string(),
    nonprofitId: v.string(),
    creator: v.string(),
    account: v.string(),
    route: v.string(),
    obligationId: v.string(),
    approvalActor: v.string(),
    approvalEvidence: v.string(),
    version: v.literal(1),
    amountCents: v.number(),
    currency: v.literal("usd"),
    destinationBinding: v.string(),
    revision: v.number(),
    source: v.string(),
    at: v.number(),
    synthetic: v.boolean(),
  })
    .index("by_obligation", ["obligationId"])
    .index("by_campaign", ["campaignSlug"]),
  fundraisingCommissionPayments: defineTable({
    obligation: v.id("fundraisingCommissionObligations"),
    campaignSlug: v.string(),
    nonprofitId: v.string(),
    creator: v.string(),
    account: v.string(),
    route: v.string(),
    paymentId: v.string(),
    actor: v.string(),
    confirmationSource: v.string(),
    amountCents: v.number(),
    currency: v.literal("usd"),
    source: v.string(),
    evidence: v.string(),
    confirmedAt: v.number(),
    at: v.number(),
    version: v.literal(1),
    synthetic: v.boolean(),
  })
    .index("by_payment", ["account", "paymentId"])
    .index("by_campaign", ["campaignSlug"]),
  fundraisingPeriodResults: defineTable({
    campaignSlug: v.string(),
    nonprofitId: v.string(),
    entryId: v.id("photoEntries"),
    periodKind: v.union(v.literal("daily"), v.literal("weekly")),
    period: v.string(),
    metric: v.literal("FUNDRAISING"),
    eligibleGrossCents: v.number(),
    originalGrossCents: v.number(),
    donationIds: v.array(v.id("fundraisingDonations")),
    source: v.string(),
    evidence: v.string(),
    actor: v.string(),
    at: v.number(),
    version: v.literal(1),
    synthetic: v.boolean(),
  }).index("by_entry", ["entryId"]),
  fundraisingFinalizedSnapshots: defineTable({
    campaignSlug: v.string(),
    nonprofitId: v.string(),
    entryId: v.id("photoEntries"),
    periodKind: v.union(v.literal("daily"), v.literal("weekly")),
    period: v.string(),
    resultId: v.string(),
    originalGrossCents: v.number(),
    winner: v.string(),
    prizeObligationId: v.string(),
    fixedPrizeCents: v.number(),
    currency: v.literal("usd"),
    source: v.string(),
    evidence: v.string(),
    actor: v.string(),
    at: v.number(),
    version: v.literal(1),
    synthetic: v.boolean(),
  })
    .index("by_entry", ["entryId"])
    .index("by_result", ["resultId"]),
  fundraisingPeriodDiscrepancies: defineTable({
    snapshotId: v.id("fundraisingFinalizedSnapshots"),
    resultId: v.id("fundraisingPeriodResults"),
    originalGrossCents: v.number(),
    correctedGrossCents: v.number(),
    source: v.string(),
    evidence: v.string(),
    actor: v.string(),
    at: v.number(),
    version: v.literal(1),
  }).index("by_snapshot", ["snapshotId"]),
  fundraisingDonations: defineTable({
    campaignSlug: v.string(),
    nonprofitId: v.string(),
    checkoutId: v.id("fundraisingCheckouts"),
    account: v.string(),
    route: v.string(),
    originEntryId: v.optional(v.id("photoEntries")),
    creator: v.optional(v.string()),
    rulesId: v.id("campaignSettings"),
    sessionId: v.string(),
    paymentId: v.string(),
    chargeId: v.string(),
    successEventId: v.string(),
    completedAt: v.number(),
    grossCents: v.number(),
    commissionCents: v.number(),
    commissionBasisPoints: v.number(),
    eligible: v.boolean(),
    earningWeek: v.string(),
    dailyPeriod: v.union(v.string(), v.null()),
    weeklyPeriod: v.union(v.string(), v.null()),
    timeBasis: v.literal("controlled-success-transition-v1"),
    actor: v.string(),
    source: v.string(),
    at: v.number(),
    version: v.literal(1),
    synthetic: v.literal(true),
  })
    .index("by_payment", ["account", "paymentId"])
    .index("by_checkout", ["checkoutId"])
    .index("by_campaign", ["campaignSlug"]),
  fundraisingLedger: defineTable({
    donationId: v.id("fundraisingDonations"),
    kind: v.union(
      v.literal("gross"),
      v.literal("refunds"),
      v.literal("fees"),
      v.literal("commission"),
    ),
    cents: v.union(v.number(), v.null()),
    providerReference: v.string(),
    digest: v.string(),
    actor: v.string(),
    source: v.string(),
    at: v.number(),
    version: v.literal(1),
  }).index("by_donation", ["donationId"]),
  fundraisingEvents: defineTable({
    account: v.string(),
    eventId: v.string(),
    checkoutId: v.id("fundraisingCheckouts"),
    donationId: v.id("fundraisingDonations"),
    digest: v.string(),
    at: v.number(),
    source: v.string(),
    version: v.literal(1),
  }).index("by_event", ["account", "eventId"]),
  fundraisingAudit: defineTable({
    checkoutId: v.id("fundraisingCheckouts"),
    action: v.string(),
    actor: v.string(),
    source: v.string(),
    at: v.number(),
    version: v.literal(1),
    digest: v.string(),
  }).index("by_checkout", ["checkoutId"]),
  // Append-only seam for the withdrawal/removal owners. Earlier earnings survive later changes.
  fundraisingCutoffs: defineTable({
    entryId: v.id("photoEntries"),
    effectiveAt: v.number(),
    reason: v.union(v.literal("withdrawal"), v.literal("ordinary-removal")),
    actor: v.string(),
    source: v.string(),
    at: v.number(),
    version: v.literal(1),
  }).index("by_entry", ["entryId"]),
};

export const refundFact = v.object({
  refundId: v.string(),
  paymentId: v.string(),
  chargeId: v.string(),
  amountCents: v.number(),
  status: v.string(),
  createdAt: v.number(),
  balanceTransactionId: v.union(v.string(), v.null()),
  failureBalanceTransactionId: v.union(v.string(), v.null()),
});
