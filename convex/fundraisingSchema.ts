import { defineTable } from "convex/server";
import { v } from "convex/values";

export const fundraisingScope = v.object({
  account: v.string(),
  route: v.string(),
  apiVersion: v.string(),
  transportBinding: v.string(),
  fixtureRunId: v.string(),
});
export const confirmation = v.object({
  checkoutId: v.id("fundraisingCheckouts"),
  sessionId: v.string(),
  paymentId: v.string(),
  chargeId: v.string(),
  eventId: v.string(),
  successEventId: v.string(),
  completedAt: v.number(),
  grossCents: v.number(),
  currency: v.literal("usd"),
  feeCents: v.union(v.number(), v.null()),
  refundedCents: v.number(),
  digest: v.string(),
  factsDigest: v.string(),
  balanceTransactionId: v.union(v.string(), v.null()),
  timeBasis: v.literal("controlled-success-transition-v1"),
});
export const fundraisingTables = {
  fundraisingCheckouts: defineTable({
    campaignSlug: v.string(),
    nonprofitId: v.string(),
    operationId: v.string(),
    fingerprint: v.string(),
    tokenHash: v.string(),
    originEntryId: v.optional(v.id("photoEntries")),
    creator: v.optional(v.string()),
    rulesId: v.id("campaignSettings"),
    amountCents: v.number(),
    applicationOrigin: v.string(),
    scope: fundraisingScope,
    state: v.union(
      v.literal("journaled"),
      v.literal("dispatched"),
      v.literal("uncertain"),
      v.literal("confirmed"),
    ),
    providerKey: v.string(),
    createdAt: v.number(),
    retryBefore: v.number(),
    sessionId: v.optional(v.string()),
    checkoutUrl: v.optional(v.string()),
    actor: v.literal("account-free-donor"),
    source: v.string(),
    version: v.literal(1),
  })
    .index("by_operation", ["operationId"])
    .index("by_session", ["sessionId"]),
  fundraisingDonations: defineTable({
    campaignSlug: v.string(),
    nonprofitId: v.string(),
    checkoutId: v.id("fundraisingCheckouts"),
    account: v.string(),
    route: v.string(),
    originEntryId: v.optional(v.id("photoEntries")),
    creator: v.optional(v.string()),
    rulesId: v.id("campaignSettings"),
    sessionId: v.string(),
    paymentId: v.string(),
    chargeId: v.string(),
    successEventId: v.string(),
    completedAt: v.number(),
    grossCents: v.number(),
    commissionCents: v.number(),
    commissionBasisPoints: v.number(),
    eligible: v.boolean(),
    earningWeek: v.string(),
    dailyPeriod: v.union(v.string(), v.null()),
    weeklyPeriod: v.union(v.string(), v.null()),
    timeBasis: v.literal("controlled-success-transition-v1"),
    actor: v.string(),
    source: v.string(),
    at: v.number(),
    version: v.literal(1),
    synthetic: v.literal(true),
  })
    .index("by_payment", ["account", "paymentId"])
    .index("by_checkout", ["checkoutId"])
    .index("by_campaign", ["campaignSlug"]),
  fundraisingLedger: defineTable({
    donationId: v.id("fundraisingDonations"),
    kind: v.union(
      v.literal("gross"),
      v.literal("refunds"),
      v.literal("fees"),
      v.literal("commission"),
    ),
    cents: v.union(v.number(), v.null()),
    providerReference: v.string(),
    digest: v.string(),
    actor: v.string(),
    source: v.string(),
    at: v.number(),
    version: v.literal(1),
  }).index("by_donation", ["donationId"]),
  fundraisingEvents: defineTable({
    account: v.string(),
    eventId: v.string(),
    checkoutId: v.id("fundraisingCheckouts"),
    donationId: v.id("fundraisingDonations"),
    digest: v.string(),
    at: v.number(),
    source: v.string(),
    version: v.literal(1),
  }).index("by_event", ["account", "eventId"]),
  fundraisingAudit: defineTable({
    checkoutId: v.id("fundraisingCheckouts"),
    action: v.string(),
    actor: v.string(),
    source: v.string(),
    at: v.number(),
    version: v.literal(1),
    digest: v.string(),
  }).index("by_checkout", ["checkoutId"]),
  // Append-only seam for the withdrawal/removal owners. Earlier earnings survive later changes.
  fundraisingCutoffs: defineTable({
    entryId: v.id("photoEntries"),
    effectiveAt: v.number(),
    reason: v.union(v.literal("withdrawal"), v.literal("ordinary-removal")),
    actor: v.string(),
    source: v.string(),
    at: v.number(),
    version: v.literal(1),
  }).index("by_entry", ["entryId"]),
};
