import { defineTable } from "convex/server";
import { v } from "convex/values";

export const paidProvider = v.union(v.literal("meta"), v.literal("tiktok"));
export const paidPlatform = v.union(
  v.literal("facebook"),
  v.literal("instagram"),
  v.literal("tiktok"),
);
export const paidMetric = v.union(
  v.literal("impressions"),
  v.literal("linkClicks"),
);
export const enrollmentInput = {
  campaignId: v.string(),
  entryId: v.id("photoEntries"),
  provider: paidProvider,
  platform: paidPlatform,
  account: v.string(),
  adId: v.string(),
  providerCampaign: v.string(),
  creativeVersion: v.number(),
  creativeDigest: v.string(),
  destination: v.string(),
  grantRevision: v.string(),
  evidence: v.string(),
  requiredPeriods: v.array(v.object({ start: v.number(), end: v.number() })),
};
export const reportRow = v.object({
  mappingId: v.id("paidMappings"),
  metric: paidMetric,
  value: v.number(),
  start: v.number(),
  end: v.number(),
  dataAsOf: v.optional(v.number()),
  revision: v.number(),
  complete: v.boolean(),
  evidence: v.string(),
});
const scoped = { campaignSlug: v.string(), nonprofitId: v.string() };
const audit = {
  actor: v.string(),
  source: v.string(),
  at: v.number(),
  version: v.literal(1),
};
export const paidMetricTables = {
  paidEnrollments: defineTable({
    ...scoped,
    ...audit,
    entryId: v.id("photoEntries"),
    provider: paidProvider,
    platform: paidPlatform,
    account: v.string(),
    adId: v.string(),
    providerCampaign: v.string(),
    creativeVersion: v.number(),
    creativeDigest: v.string(),
    destination: v.string(),
    grantRevision: v.string(),
    evidence: v.string(),
    synthetic: v.boolean(),
    requiredPeriods: v.array(v.object({ start: v.number(), end: v.number() })),
  }).index("by_campaign", ["campaignSlug"]),
  paidMappings: defineTable({
    ...scoped,
    ...audit,
    enrollmentId: v.id("paidEnrollments"),
    sourceId: v.id("paidSources"),
    entryId: v.id("photoEntries"),
    provider: paidProvider,
    account: v.string(),
    platform: paidPlatform,
    adId: v.string(),
    active: v.boolean(),
    revokedAt: v.optional(v.number()),
    revokedBy: v.optional(v.string()),
  })
    .index("by_source", ["sourceId"])
    .index("by_campaign", ["campaignSlug"])
    .index("by_placement", ["provider", "account", "adId", "platform"]),
  paidRequiredPeriods: defineTable({
    ...scoped,
    ...audit,
    mappingId: v.id("paidMappings"),
    start: v.number(),
    end: v.number(),
    evidence: v.string(),
  }).index("by_mapping", ["mappingId"]),
  paidPeriods: defineTable({
    ...scoped,
    ...audit,
    label: v.string(),
    start: v.number(),
    end: v.number(),
    mappingIds: v.array(v.id("paidMappings")),
  }).index("by_campaign", ["campaignSlug"]),
  paidSources: defineTable({
    ...scoped,
    provider: paidProvider,
    account: v.string(),
    active: v.boolean(),
    activatedAt: v.number(),
    lastSuccess: v.optional(v.number()),
    revision: v.number(),
    generation: v.number(),
    watchGeneration: v.number(),
    dueAt: v.optional(v.number()),
    nextAt: v.number(),
    incidentSequence: v.number(),
    outage: v.boolean(),
    statusReason: v.string(),
    synthetic: v.boolean(),
    freshnessMs: v.literal(900_000),
    retryHold: v.optional(v.string()),
  }).index("by_campaign", ["campaignSlug"]),
  paidOperations: defineTable({
    ...scoped,
    ...audit,
    operationId: v.string(),
    sourceId: v.id("paidSources"),
    periodId: v.id("paidPeriods"),
    generation: v.number(),
    inputRevision: v.number(),
    mappingIds: v.array(v.id("paidMappings")),
    state: v.string(),
    reason: v.string(),
    startedAt: v.optional(v.number()),
    finishedAt: v.optional(v.number()),
    leaseUntil: v.optional(v.number()),
    fingerprint: v.optional(v.string()),
    retryAt: v.optional(v.number()),
    reportedRows: v.optional(v.array(reportRow)),
  })
    .index("by_operation", ["campaignSlug", "operationId"])
    .index("by_source", ["sourceId"]),
  paidCoverage: defineTable({
    ...scoped,
    entryId: v.id("photoEntries"),
    mappingId: v.id("paidMappings"),
    sourceId: v.id("paidSources"),
    periodId: v.id("paidPeriods"),
    metric: paidMetric,
    inputRevision: v.number(),
    generation: v.number(),
    operationId: v.id("paidOperations"),
    complete: v.boolean(),
    reason: v.string(),
    observedAt: v.number(),
    currentDataAsOf: v.optional(v.number()),
    provenance: v.literal("owned-controlled-unvalidated"),
  }).index("by_scope", ["mappingId", "periodId", "metric"]),
  paidObservations: defineTable({
    ...scoped,
    ...audit,
    mappingId: v.id("paidMappings"),
    entryId: v.id("photoEntries"),
    sourceId: v.id("paidSources"),
    periodId: v.id("paidPeriods"),
    metric: paidMetric,
    value: v.number(),
    revision: v.number(),
    dataAsOf: v.number(),
    evidence: v.string(),
    fingerprint: v.string(),
    operationId: v.id("paidOperations"),
  }).index("by_scope", ["mappingId", "periodId", "metric"]),
  paidAudit: defineTable({
    ...scoped,
    ...audit,
    action: v.string(),
    reference: v.string(),
    evidence: v.string(),
  }).index("by_campaign", ["campaignSlug"]),
};
