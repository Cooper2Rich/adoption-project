import { defineTable } from "convex/server";
import { v } from "convex/values";

export const incidentKinds = [
  "import-outage",
  "prize-replenishment",
  "batch-ready",
  "public-media-outage",
  "prize-loss",
  "capacity-waiting",
  "stopping-failed",
  "stopping-uncertain",
  "delivery-unavailable",
  "evaluation-interrupted",
  "pause-reserved-slot",
  "financial-safety-pause",
  "initial-trial-coverage",
  "launch-blocker",
  "fundraising-discrepancy",
  "commission-overpayment",
  "fundraising-refund-held",
] as const;
export const incidentKind = v.union(
  ...incidentKinds.map((kind) => v.literal(kind)),
);
export const incidentObservation = {
  campaignId: v.string(),
  key: v.string(),
  kind: incidentKind,
  sequence: v.number(),
  observedAt: v.number(),
  active: v.boolean(),
  reason: v.string(),
  evidence: v.string(),
  resolutionRole: v.union(
    v.literal("manager"),
    v.literal("administrator"),
    v.literal("manager-and-administrator"),
  ),
};
export const observationValidator = v.object(incidentObservation);
const state = v.union(
  ...[
    "pending",
    "sending",
    "unknown",
    "accepted",
    "delivered",
    "failed",
    "held",
  ].map((value) => v.literal(value)),
);
export const incidentTables = {
  operatorContactAudit: defineTable({
    campaignSlug: v.string(),
    nonprofitId: v.string(),
    subject: v.string(),
    actor: v.string(),
    action: v.string(),
    source: v.string(),
    at: v.number(),
    version: v.literal(1),
  }).index("by_campaign", ["campaignSlug"]),
  operatorContacts: defineTable({
    nonprofitId: v.string(),
    subject: v.string(),
    email: v.string(),
    verifiedAt: v.number(),
    source: v.string(),
  }).index("by_person", ["nonprofitId", "subject"]),
  operatorRouting: defineTable({
    campaignSlug: v.string(),
    nonprofitId: v.string(),
    designatedOperator: v.string(),
    actor: v.string(),
    at: v.number(),
    version: v.literal(1),
  }).index("by_campaign", ["campaignSlug"]),
  incidentHeads: defineTable({
    campaignSlug: v.string(),
    key: v.string(),
    kind: incidentKind,
    producer: v.string(),
    sequence: v.number(),
    observedAt: v.number(),
    incidentId: v.optional(v.id("operatorIncidents")),
  }).index("by_stream", ["campaignSlug", "key"]),
  operatorIncidents: defineTable({
    campaignSlug: v.string(),
    nonprofitId: v.string(),
    key: v.string(),
    kind: incidentKind,
    reason: v.string(),
    resolutionRole: v.string(),
    status: v.union(v.literal("open"), v.literal("resolved")),
    detectedAt: v.number(),
    firstObservedAt: v.number(),
    updatedAt: v.number(),
    resolvedAt: v.optional(v.number()),
    originalEvidence: v.string(),
    producer: v.string(),
    synthetic: v.boolean(),
    version: v.literal(1),
  }).index("by_campaign", ["campaignSlug"]),
  incidentEvidence: defineTable({
    incidentId: v.id("operatorIncidents"),
    sequence: v.number(),
    observedAt: v.number(),
    at: v.number(),
    actor: v.string(),
    source: v.string(),
    evidence: v.string(),
    reason: v.string(),
    active: v.boolean(),
    version: v.literal(1),
  }).index("by_incident", ["incidentId"]),
  incidentNotices: defineTable({
    incidentId: v.id("operatorIncidents"),
    kind: v.union(v.literal("detection"), v.literal("recovery")),
    createdAt: v.number(),
    title: v.string(),
    text: v.string(),
    routing: v.string(),
    hold: v.optional(v.string()),
  }).index("by_incident", ["incidentId"]),
  incidentEmails: defineTable({
    noticeId: v.id("incidentNotices"),
    incidentId: v.id("operatorIncidents"),
    subject: v.string(),
    email: v.string(),
    recipientRole: v.string(),
    from: v.string(),
    title: v.string(),
    text: v.string(),
    routing: v.string(),
    state,
    hold: v.optional(v.string()),
    createdAt: v.number(),
    nextAt: v.number(),
    failures: v.number(),
    wakeVersion: v.number(),
    activeAttempt: v.optional(v.id("incidentEmailAttempts")),
  })
    .index("by_notice", ["noticeId"])
    .index("by_notice_state", ["noticeId", "state"]),
  incidentEmailAttempts: defineTable({
    emailId: v.id("incidentEmails"),
    ordinal: v.number(),
    key: v.string(),
    payload: v.string(),
    providerBinding: v.string(),
    state,
    journaledAt: v.number(),
    sendStartedAt: v.number(),
    lastTransportAt: v.number(),
    transportCalls: v.number(),
    leaseUntil: v.number(),
    providerId: v.optional(v.string()),
    providerEvent: v.optional(v.string()),
    finishedAt: v.optional(v.number()),
    source: v.string(),
    version: v.literal(1),
  }).index("by_email", ["emailId"]),
};
