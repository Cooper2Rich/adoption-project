import { defineTable } from "convex/server";
import { v } from "convex/values";

const scope = { campaignSlug: v.string(), nonprofitId: v.string() };
const audit = {
  actor: v.string(),
  source: v.string(),
  at: v.number(),
  version: v.literal(1),
};
export const prizeEvidenceInput = v.object({
  campaignId: v.string(),
  nonprofitId: v.string(),
  revision: v.string(),
  account: v.string(),
  financialAccountBinding: v.string(),
  route: v.string(),
  sourcePurpose: v.literal("fundraising"),
  destinationPurpose: v.literal("prize"),
  beneficiary: v.string(),
  destination: v.string(),
  transportBinding: v.string(),
  authorityRevision: v.string(),
  manager: v.string(),
  approvedAmountCents: v.number(),
  fundraisingCents: v.union(v.number(), v.null()),
  prizeCents: v.union(v.number(), v.null()),
  advertisingCents: v.union(v.number(), v.null()),
  reservedCreatorCents: v.number(),
  refundHoldCents: v.number(),
  reflectedRefunds: v.array(
    v.object({
      account: v.string(),
      refundId: v.string(),
      amountCents: v.number(),
    }),
  ),
  otherFundraisingObligationsCents: v.number(),
  advertisingObligationsCents: v.number(),
  reflectedTransfers: v.array(v.string()),
  sourceReflectedTransfers: v.array(v.string()),
  observedAt: v.number(),
  expiresAt: v.number(),
  sequence: v.number(),
  evidence: v.string(),
});
export const prizeTables = {
  prizeClocks: defineTable({ campaignSlug: v.string(), now: v.number() }).index(
    "by_campaign",
    ["campaignSlug"],
  ),
  prizeEvidence: defineTable({
    ...scope,
    ...audit,
    input: prizeEvidenceInput,
    synthetic: v.boolean(),
    expired: v.boolean(),
  }).index("by_campaign", ["campaignSlug"]),
  prizeOccurrences: defineTable({
    ...scope,
    ...audit,
    settingsId: v.id("campaignSettings"),
    local: v.string(),
    executionAt: v.union(v.number(), v.null()),
    advanceAt: v.union(v.number(), v.null()),
    amountCents: v.number(),
    state: v.string(),
    reason: v.string(),
    initializedAt: v.number(),
    advanceCheckedAt: v.optional(v.number()),
    advanceAvailableCents: v.optional(v.union(v.number(), v.null())),
    nextAt: v.optional(v.number()),
    checkedAt: v.optional(v.number()),
    availableCents: v.optional(v.union(v.number(), v.null())),
    generation: v.number(),
    transferId: v.optional(v.id("prizeTransfers")),
  }).index("by_campaign", ["campaignSlug"]),
  prizeTransfers: defineTable({
    ...scope,
    ...audit,
    occurrenceId: v.id("prizeOccurrences"),
    evidenceId: v.id("prizeEvidence"),
    key: v.string(),
    amountCents: v.number(),
    currency: v.literal("USD"),
    revision: v.string(),
    account: v.string(),
    route: v.string(),
    sourcePurpose: v.literal("fundraising"),
    destinationPurpose: v.literal("prize"),
    beneficiary: v.string(),
    destination: v.string(),
    transportBinding: v.string(),
    authorityRevision: v.string(),
    manager: v.string(),
    state: v.string(),
    generation: v.number(),
    nextAt: v.number(),
    providerId: v.optional(v.string()),
    settlementReference: v.optional(v.string()),
    settledAt: v.optional(v.number()),
    conflict: v.optional(v.boolean()),
  }).index("by_campaign", ["campaignSlug"]),
  prizeAudit: defineTable({
    ...scope,
    ...audit,
    reference: v.string(),
    action: v.string(),
    evidence: v.string(),
  }).index("by_campaign", ["campaignSlug"]),
  prizeObservations: defineTable({
    transferId: v.id("prizeTransfers"),
    ...audit,
    generation: v.number(),
    outcome: v.string(),
    digest: v.string(),
    providerId: v.optional(v.string()),
    settlementReference: v.optional(v.string()),
  }).index("by_transfer", ["transferId"]),
};
